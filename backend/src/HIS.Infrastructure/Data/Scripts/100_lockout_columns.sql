-- #366 AUTHZ-0: thêm cột lockout cho Users
IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='Users' AND COLUMN_NAME='FailedLoginCount')
    ALTER TABLE Users ADD FailedLoginCount INT NOT NULL DEFAULT 0;

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='Users' AND COLUMN_NAME='LockoutEndAt')
    ALTER TABLE Users ADD LockoutEndAt DATETIME2 NULL;
